-- thermal :: build
--
--   nvim -l scripts/build.lua
--
-- Regenerates every derived file from lua/thermal/palette.lua. Run after any
-- palette edit and after adding a flavour, then commit the result.
--
-- Uses only Neovim, which you already have on every machine this theme targets.
-- No node, no cargo, no python.

-- Absolutise first (source may be relative when invoked as `nvim -l scripts/...`),
-- then strip the script suffix to get the repo root.
local root = vim.fn.fnamemodify(debug.getinfo(1, "S").source:sub(2), ":p")
  :gsub("/scripts/build%.lua$", "")
local palette = dofile(root .. "/lua/thermal/palette.lua")
local adapter = dofile(root .. "/lua/thermal/catppuccin.lua")

local written = {}

local function write(relpath, body)
  local path = root .. "/" .. relpath
  vim.fn.mkdir(vim.fn.fnamemodify(path, ":h"), "p")
  local f = assert(io.open(path, "wb"), "cannot write " .. path)
  f:write(body)
  f:close()
  table.insert(written, relpath)
end

local GENERATED = "-- GENERATED by scripts/build.lua -- do not edit\n"

--- "#RRGGBB" -> "[R, G, B]" for Chrome theme colour arrays.
local function hex2rgb(hex)
  local r = tonumber(hex:sub(2, 3), 16)
  local g = tonumber(hex:sub(4, 5), 16)
  local b = tonumber(hex:sub(6, 7), 16)
  return ("[%d, %d, %d]"):format(r, g, b)
end

