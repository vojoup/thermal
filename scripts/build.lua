-- Stub palette modules. catppuccin's get_palette does
--   local _, palette = pcall(require, "catppuccin.palettes." .. flavour)
-- and on failure leaves `palette` as the ERROR STRING, which then reaches
-- tbl_deep_extend and crashes the compiler. So the module has to exist. It can
-- be empty: the real colours arrive via color_overrides, which is what
-- catppuccin hashes to decide when to recompile.
for _, name in ipairs(palette.order) do
  write(
    ("lua/catppuccin/palettes/thermal_%s.lua"):format(name),
    GENERATED .. "-- intentionally empty; see lua/thermal/catppuccin.lua\nreturn {}\n"
  )
end

