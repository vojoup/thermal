-- A thin, SELF-CONTAINED tmux plugin. Its structure is lifted from
-- niksingh710/minimal-tmux-status (MIT) -- transparent bar, centred windows,
-- prefix indicator -- but the colours are thermal's and baked in, so there is
-- no runtime dependency and nothing is pulled at build time. It installs with
-- tpm exactly like the plugin it is based on:  set -g @plugin 'vojoup/thermal'.
--
-- The bar is smoke (status-style bg=default,fg=default, so it inherits the
-- terminal). The heat -- amber -- lands only on the CURRENT window and the
-- prefix indicator: the same move as the cursor line, search hit and Slack
-- active item. Active pane border is amber too; copy-mode and the command
-- prompt take the selection colours. All three flavours are baked in and
-- picked at runtime with `set -g @thermal-tmux-flavour void`.
--
-- tpm runs root-level *.tmux files, so this lives at the repo root, executable.

-- Baked palette: one bash case arm per flavour, plus a `*` arm = the default.
local flavour_cases = {}
for _, name in ipairs(palette.order) do
  local p = palette.flavours[name]
  table.insert(flavour_cases, ("    %s) bg_d=%q fg_d=%q border=%q sel=%q hi=%q ;;")
    :format(name, p.amber, p.bg, p.border, p.bg_sel, p.fg_hi))
end
do
  local p = palette.flavours[palette.default]
  table.insert(flavour_cases, ("    *) bg_d=%q fg_d=%q border=%q sel=%q hi=%q ;;")
    :format(p.amber, p.bg, p.border, p.bg_sel, p.fg_hi))
end

local tmux_plugin = ([=[#!/usr/bin/env bash
