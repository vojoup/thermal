# in -- the same move as the cursor line and search hit in the editor.

get() {
  # value of a tmux user option, or a fallback when it is unset
  local v
  v=$(tmux show-options -gqv "$1")
  [ -n "$v" ] && echo "$v" || echo "$2"
}

# ---- flavour -> baked palette --------------------------------------------
# Pick with:  set -g @thermal-tmux-flavour void   (smoky | void | ash)
flavour=$(get "@thermal-tmux-flavour" "%s")
case "$flavour" in
%s
esac

# bg is the heat, fg the flavour's own smoke; override either if you want.
bg=$(get "@thermal-tmux-bg" "$bg_d")
