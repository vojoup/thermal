---------------------------------------------------------------- chrome ------
-- One unpacked-extension theme per flavour. Chrome themes are a manifest with a
-- `theme` block of RGB triplets: frame (the strip behind the tabs) is the
-- darkest smoke, the toolbar is a raised smoke surface (bg_hl), and the heat --
-- amber -- lands only on NTP links, the same move as the cursor line.
--
-- The toolbar is deliberately a clear step lighter than the frame. Chrome has no
-- "selected tab" colour key: multi-selected (and active) inactive tabs are
-- painted with the TOOLBAR colour, unselected tabs with the FRAME colour. If the
-- two are close, a multi-selection is invisible -- so the gap between frame
-- (bg_dark) and toolbar (bg_hl) is what makes selected tabs read.
--
-- Colours are baked in; there is no build-time or runtime dependency. Load with
-- chrome://extensions -> Developer mode -> Load unpacked, pointing at one
-- flavour's directory. See chrome/README.md.
--
-- Icons are tinted light via `tints.buttons` (HSL, lightness ~0.83) rather than
-- a colour key, which is how a dark Chrome theme keeps toolbar glyphs legible.
for _, name in ipairs(palette.order) do
  local p = palette.flavours[name]
  -- key -> palette hex. Order here is the order in the file.
  local colors = {
    { "frame", p.bg_dark },
    { "frame_inactive", p.bg_dark },
    { "frame_incognito", p.bg_dark },
    { "frame_incognito_inactive", p.bg_dark },
    { "toolbar", p.bg_hl }, -- raised surface; also the active/selected tab bg
    { "toolbar_text", p.fg },
    { "toolbar_button_icon", p.fg },
    { "tab_text", p.fg_hi },
    { "tab_background_text", p.muted },
    { "tab_background_text_inactive", p.dim },
    { "bookmark_text", p.fg },
    { "ntp_background", p.bg },
    { "ntp_text", p.fg },
    { "ntp_link", p.amber },
    { "button_background", p.bg_sel },
    { "omnibox_background", p.bg }, -- inset: darker than the raised toolbar
    { "omnibox_text", p.fg },
  }
  local color_lines = {}
  for _, kv in ipairs(colors) do
    table.insert(color_lines, ('      "%s": %s'):format(kv[1], hex2rgb(kv[2])))
  end
  local manifest = ([[{
  "manifest_version": 3,
  "version": "1.0.0",
  "name": "Thermal (%s)",
  "description": "thermal -- a dark, low-contrast theme based on the PBTfans Thermal keycap set. github.com/vojoup/thermal",
  "theme": {
    "colors": {
%s
    },
    "tints": {
      "buttons": [-1.0, -1.0, 0.83]
    },
    "properties": {
      "ntp_background_alignment": "bottom",
      "ntp_logo_alternate": 1
    }
  }
}
]]):format(name, table.concat(color_lines, ",\n"))
  write(("chrome/thermal-%s/manifest.json"):format(name), manifest)
end

