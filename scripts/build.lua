-- Eight comma-separated values: column bg, menu hover bg, active item,
-- active item text, hover item, text, active presence, mention badge.
-- Paste into Preferences > Appearance > Custom theme.
--
-- Sidebar only -- Slack gives no way to reach the message pane, so pair with
-- Appearance > Dark or the panes won't match.
--
-- One file per flavour, containing ONLY the string, so that all of these work:
--   cat slack/thermal-void.txt | pbcopy
--   :ThermalCopy slack void
--   opening the file on GitHub and hitting copy
local slack_rows = {}
for _, name in ipairs(palette.order) do
  local p = palette.flavours[name]
  local str = table.concat({
    p.bg, -- column bg
    p.bg_alt, -- menu hover bg
    p.bg_sel, -- active item bg
    p.amber, -- active item text  <- the heat marks where you are
    p.bg_hl, -- hover item bg
    p.fg, -- text
    p.frost, -- presence dot (teal stands in for green)
    p.ember, -- mention badge
  }, ",")
  write(("slack/thermal-%s.txt"):format(name), str .. "\n")
  table.insert(slack_rows, ("| `%s` | `%s` |"):format(name, str))
end

