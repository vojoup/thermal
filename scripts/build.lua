-- Save to ~/.config/ghostty/themes/ then `theme = thermal-smoky` in your config.
-- For a light/dark pair: `theme = light:thermal-ash,dark:thermal-void`.
for _, name in ipairs(palette.order) do
  local p = palette.flavours[name]
  local out = { ("# thermal-%s -- generated, see github.com/vojoup/thermal"):format(name), "" }
  for i, hex in ipairs(adapter.ansi(p)) do
    table.insert(out, ("palette = %d=%s"):format(i - 1, hex))
  end
  vim.list_extend(out, {
    "",
    "background = " .. p.bg,
    "foreground = " .. p.fg,
    "cursor-color = " .. p.amber,
    "cursor-text = " .. p.bg,
    "selection-background = " .. p.bg_sel,
    "selection-foreground = " .. p.fg_hi,
    "",
  })
  write("ghostty/thermal-" .. name, table.concat(out, "\n"))
end

